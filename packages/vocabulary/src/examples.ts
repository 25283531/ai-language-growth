function firstMeaning(meaningZh: string): string {
  return (meaningZh || '').split(/[；;]/)[0]?.trim() || '';
}

function predicateZh(meaning: string): string {
  return meaning.endsWith('的') ? meaning : `${meaning}的`;
}

function bareZh(meaning: string): string {
  return meaning.replace(/的$/, '');
}

function isPeople(word: string, meaning: string): boolean {
  if (/(国家|家乡|家园|家庭)$/.test(meaning)) return false;
  return PEOPLE.has(word) || PEOPLE_ZH_RE.test(meaning);
}

function isPlace(word: string, meaning: string): boolean {
  return PLACES.has(word) || PLACE_ZH_RE.test(meaning);
}

function capitalize(text: string): string {
  return text.charAt(0).toUpperCase() + text.slice(1);
}

