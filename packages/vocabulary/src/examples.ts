function nounExample(word: string, meaning: string, domains: string[]): ChildExample {
  if (isPeople(word, meaning)) {
    if (PLURAL_PEOPLE.has(word)) return { en: `The ${word} are kind.`, zh: `这些${meaning}很和善。` };
    return { en: `The ${word} is kind.`, zh: `这位${meaning}很和善。` };
  }
  if (isPlace(word, meaning)) return { en: `I go to the ${word}.`, zh: `我去${meaning}。` };
  if (LIKE_NOUNS.has(word)) {
    return { en: `I like the ${word}.`, zh: `我喜欢${meaning}。` };
  }
  if (domains.includes('animals')) return { en: `I see the ${word}.`, zh: `我看见${meaning}。` };
  if (CONCRETE_HINTS.test(meaning) || MEASURE_WORDS[word] || UNCOUNTABLE.has(word)) {
    return { en: `I see the ${word}.`, zh: `我看见${meaning}。` };
  }
  return { en: `We talk about the ${word}.`, zh: `我们谈论${meaning}。` };
}

function adjectiveExample(word: string, meaning: string): ChildExample {
  const predicate = predicateZh(meaning);
  if (EMOTION_ADJECTIVES.has(word)) return { en: `I am ${word}.`, zh: `我很${bareZh(meaning)}。` };
  if (ATTRIBUTIVE_ADJECTIVES.has(word)) {
    return { en: `I like the ${word} one.`, zh: `我喜欢${predicate}那个。` };
  }
  if (PREDICATIVE_ADJECTIVES.has(word)) return { en: `It is ${word}.`, zh: `它是${predicate}。` };
  return { en: `It is ${word}.`, zh: `它是${predicate}。` };
}

function adverbExample(word: string, meaning: string): ChildExample {
  if (FREQUENCY_ADVERBS.has(word)) return { en: `I ${word} read books.`, zh: `我${meaning}读书。` };
  if (DEGREE_ADVERBS.has(word)) return { en: `I am ${word} happy.`, zh: `我${meaning}开心。` };
  if (SENTENCE_ADVERBS.has(word)) return { en: `${capitalize(word)}, I am happy.`, zh: `${meaning}，我很开心。` };
  if (PLACE_ADVERBS.has(word)) return { en: `I play ${word}.`, zh: `我在${meaning}玩。` };
  return { en: `I read ${word}.`, zh: `我${meaning}读书。` };
}

function verbExample(word: string, meaning: string, pos: string): ChildExample {
  if (STATE_VERBS.has(word)) return { en: `I ${word} it.`, zh: `我${meaning}它。` };
  if (NO_IT_VERBS.has(word) || pos === 'vi.') return { en: `I can ${word}.`, zh: `我能${meaning}。` };
  return { en: `I can ${word} it.`, zh: `我能${meaning}它。` };
}

function numberExample(word: string, meaning: string): ChildExample {
  return { en: `I have ${word} apples.`, zh: `我有${NUMBER_ZH[word] || firstMeaning(meaning)}个苹果。` };
}

export function applyChildSenseOverrides<T extends SenseInput>(entries: T[]): T[] {
  return entries.map((entry) => {
    const override = CHILD_SENSE_OVERRIDES[entry.word.trim().toLowerCase()];
    return override ? { ...entry, ...override } : entry;
  });
}

export function buildChildSafeExample(entry: ExampleInput): ChildExample {
  const word = entry.word.trim().toLowerCase();
  const curated = CURATED_EXAMPLES[word] || EXTRA_CURATED[word];
  if (curated) return curated;

  const meaning = firstMeaning(entry.meaningZh);
  const pos = (entry.pos || '').trim().toLowerCase();
  const domains = entry.domains ?? [];
  if (pos.startsWith('n.')) return nounExample(word, meaning, domains);
  if (pos.startsWith('a.') || pos.startsWith('adj.')) return adjectiveExample(word, meaning);
  if (pos.startsWith('adv.')) return adverbExample(word, meaning);
  if (/^(v|vt|vi)\.?$/.test(pos)) return verbExample(word, meaning, pos);
  if (pos.startsWith('num.')) return numberExample(word, meaning);
  if (entry.isFunctionWord) return { en: `I use the word "${word}".`, zh: `我学习单词“${meaning}”。` };
  return { en: `I know the word "${word}".`, zh: `我认识单词“${meaning}”。` };
}

export function applyChildSafeExamples<T extends ExampleInput & { examples: ChildExample[] }>(
  entries: T[],
  options: { limit?: number; tags?: string[]; coreOnly?: boolean; skipUnsafe?: boolean } = {},
): T[] {
  const limit = options.limit ?? entries.length;
  const tags = options.tags?.map((tag) => tag.toLowerCase()) ?? [];
  const skipUnsafe = options.skipUnsafe ?? true;
  let count = 0;
  return entries.map((entry) => {
    if (count >= limit) return entry;
    if (options.coreOnly && !entry.isCore) return entry;
    if (skipUnsafe && entry.childSafe === false) return entry;
    if (tags.length && !tags.some((tag) => entry.tags?.map((item) => item.toLowerCase()).includes(tag))) return entry;
    count += 1;
    return { ...entry, examples: [buildChildSafeExample(entry)] };
  });
}
